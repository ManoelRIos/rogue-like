ACCENTS = {
    'Á': ('A', ['...#.', '..#..']), 'À': ('A', ['.#...', '..#..']), 'Â': ('A', ['..#..', '.#.#.']), 'Ã': ('A', ['.#.#.', '#.#..']),
    'É': ('E', ['...#.', '..#..']), 'Ê': ('E', ['..#..', '.#.#.']), 'Í': ('I', ['...#.', '..#..']),
    'Ó': ('O', ['...#.', '..#..']), 'Ô': ('O', ['..#..', '.#.#.']), 'Õ': ('O', ['.#.#.', '#.#..']), 'Ú': ('U', ['...#.', '..#..']),
}

CELL_W, CELL_H = 6, 10
COLS = 16


def build_font():
    chars = list(G.keys()) + list(ACCENTS.keys()) + ['Ç']
    rows = (len(chars) + COLS - 1) // COLS
    img = Image.new('RGBA', (COLS * CELL_W, rows * CELL_H), (0, 0, 0, 0))
    p = img.load()
    for i, ch in enumerate(chars):
        ox, oy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        if ch in G:
            glyph, acc = G[ch], None
        elif ch == 'Ç':
            glyph, acc = G['C'], None
        else:
            base, acc = ACCENTS[ch]
            glyph = G[base]
        for y, row in enumerate(glyph):
            for x, c in enumerate(row):
                if c == '#':
                    p[ox + x, oy + 2 + y] = (255, 255, 255, 255)
        if acc:
            for y, row in enumerate(acc):
                for x, c in enumerate(row):
                    if c == '#':
                        p[ox + x, oy + y] = (255, 255, 255, 255)
        if ch == 'Ç':
            p[ox + 2, oy + 9] = (255, 255, 255, 255)
            p[ox + 1, oy + 9] = (255, 255, 255, 255)
    return img, ''.join(chars)
